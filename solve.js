// A faster drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
//
// run(input) returns exactly the output tree makefun-site 1.0.0's build returns
// for the same input: a JSON object of every path it writes and that file's text,
// byte for byte. Written from scratch against the reference's README and behaviour
// (front matter, template dialect, Markdown subset, slug rule, report). Nothing is
// copied from the reference's code: the structure below is my own, shaped for speed
// (single-pass Markdown, bulk plain-text copying in inline rendering, an ASCII
